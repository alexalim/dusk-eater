# Packs the painted skin pictures (design/art/skins/<art>.png, 192 px RGBA) into www/skin-art.js as webp data URIs.
# One source for the shop pictures and the in-game character card: a data URI is same-origin everywhere, so WebGL
# takes it as a texture in the app, in a browser and from file:// alike.
# Usage: python3 tools/skins/pack.py   (from the repository root; needs Pillow)
import base64, io, pathlib
from PIL import Image
root = pathlib.Path(__file__).resolve().parents[2]
rows = []
for f in sorted((root / 'design/art/skins').glob('*.png')):
    buf = io.BytesIO(); Image.open(f).convert('RGBA').save(buf, 'WEBP', quality=90, method=6)
    rows.append(f"    {f.stem}: 'data:image/webp;base64,{base64.b64encode(buf.getvalue()).decode()}',")
out = root / 'www/skin-art.js'
out.write_text("// Generated by tools/skins/pack.py from design/art/skins: do not edit by hand.\n(function (root) {\n  'use strict';\n  root.DuskSkinArt = {\n"
               + '\n'.join(rows) + "\n  };\n})(this);\n", encoding='utf-8')
print(len(rows), 'pictures,', out.stat().st_size // 1024, 'KB')
